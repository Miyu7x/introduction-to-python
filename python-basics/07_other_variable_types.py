# Notes

# int - whole numbers, no decimal. 100, 4, 0, -5. Counting things.
  
# float - numbers with a decimal point. 1.1, 3.14, 10.0. The .0 matters, even if it looks like a whole number. 
# Python treats 10 and 10.0 differently.

# str - text. Anything in quotes. "hello", "Renata", "100". 
# That last one is important: "100" is not the same as 100. One is text, one is a number. 
# You can't do math on "100".

# bool - only two possible values ever: True or False. That's it. 
# You'll use these constantly in security work: is this IP on the blocklist? 
# Is the user authenticated? Yes or no, true or false.

